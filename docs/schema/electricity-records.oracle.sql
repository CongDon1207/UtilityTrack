CREATE TABLE ELECTRICITY_RECORDS (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
  RECORD_YEAR NUMBER(4) NOT NULL,
  RECORD_MONTH NUMBER(2) NOT NULL,
  LOCATION VARCHAR2(50) NOT NULL,
  DEPARTMENT_GROUP VARCHAR2(150) NOT NULL,
  KWH_USED NUMBER(14) NOT NULL,
  TOTAL_COST NUMBER(18) NOT NULL,
  NOTE VARCHAR2(500),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT PK_ELECTRICITY_RECORDS PRIMARY KEY (ID),
  CONSTRAINT CK_ELEC_RECORD_MONTH CHECK (RECORD_MONTH BETWEEN 1 AND 12),
  CONSTRAINT CK_ELEC_KWH_USED CHECK (KWH_USED >= 0),
  CONSTRAINT CK_ELEC_TOTAL_COST CHECK (TOTAL_COST >= 0),
  CONSTRAINT UQ_ELEC_RECORD_SCOPE UNIQUE (
    RECORD_YEAR,
    RECORD_MONTH,
    LOCATION,
    DEPARTMENT_GROUP
  )
);
