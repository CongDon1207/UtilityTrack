CREATE TABLE VEHICLES (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
  VEHICLE_NAME VARCHAR2(100) NOT NULL,
  IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT PK_VEHICLES PRIMARY KEY (ID),
  CONSTRAINT UQ_VEHICLES_NAME UNIQUE (VEHICLE_NAME),
  CONSTRAINT CK_VEHICLES_IS_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE VEHICLE_KM_RECORDS (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
  VEHICLE_ID NUMBER NOT NULL,
  TRIP_DATE DATE NOT NULL,
  DRIVER_NAME VARCHAR2(100),
  TRIP_PURPOSE VARCHAR2(300),
  DEPARTURE_TIME VARCHAR2(5),
  DEPARTURE_ODOMETER NUMBER(10) NOT NULL,
  ARRIVAL_TIME VARCHAR2(5),
  ARRIVAL_ODOMETER NUMBER(10) NOT NULL,
  NOTE VARCHAR2(500),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT PK_VEHICLE_KM_RECORDS PRIMARY KEY (ID),
  CONSTRAINT FK_KM_RECORDS_VEHICLE FOREIGN KEY (VEHICLE_ID)
    REFERENCES VEHICLES (ID),
  CONSTRAINT CK_KM_DEPARTURE_ODOMETER CHECK (DEPARTURE_ODOMETER >= 0),
  CONSTRAINT CK_KM_ARRIVAL_ODOMETER CHECK (ARRIVAL_ODOMETER >= 0),
  CONSTRAINT CK_KM_ODOMETER_ORDER CHECK (ARRIVAL_ODOMETER >= DEPARTURE_ODOMETER)
);

CREATE TABLE FUEL_RECORDS (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
  VEHICLE_ID NUMBER NOT NULL,
  FUEL_DATE DATE NOT NULL,
  UNIT_PRICE NUMBER(18, 2) NOT NULL,
  LITERS NUMBER(14, 2) NOT NULL,
  NOTE VARCHAR2(500),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT PK_FUEL_RECORDS PRIMARY KEY (ID),
  CONSTRAINT FK_FUEL_RECORDS_VEHICLE FOREIGN KEY (VEHICLE_ID)
    REFERENCES VEHICLES (ID),
  CONSTRAINT CK_FUEL_UNIT_PRICE CHECK (UNIT_PRICE >= 0),
  CONSTRAINT CK_FUEL_LITERS CHECK (LITERS >= 0)
);
